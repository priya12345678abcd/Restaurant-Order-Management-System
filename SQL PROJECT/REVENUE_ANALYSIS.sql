#6. Calculate restaurant-wise revenue
SELECT
    r.restaurant_id,
    r.restaurant_name,
    SUM(o.total_amount) AS total_revenue
FROM restaurants r
JOIN orders o
    ON r.restaurant_id = o.restaurant_id
WHERE o.order_status = 'Delivered'
GROUP BY
    r.restaurant_id,
    r.restaurant_name
ORDER BY total_revenue DESC;


# Concept: JOIN, SUM(), GROUP BY, ORDER BY

# Explanation:
- JOIN connects the restaurants and orders tables.
- SUM() calculates the total revenue generated by each restaurant.
- GROUP BY groups revenue restaurant-wise.
- ORDER BY displays the highest revenue-generating restaurants first.
