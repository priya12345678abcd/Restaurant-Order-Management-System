#8. Rank restaurants by revenue
SELECT
    restaurant_id,
    restaurant_name,
    total_revenue,
    RANK() OVER (
        ORDER BY total_revenue DESC
    ) AS revenue_rank
FROM (
    SELECT
        r.restaurant_id,
        r.restaurant_name,
        SUM(o.total_amount) AS total_revenue
    FROM restaurants r
    JOIN orders o
        ON r.restaurant_id = o.restaurant_id
    WHERE o.order_status = 'Delivered'
    GROUP BY
        r.restaurant_id,
        r.restaurant_name
) AS restaurant_revenue;


# Concept: JOIN, SUM(), GROUP BY, Subquery, RANK(), Window Function

# Explanation:
- The inner query calculates total revenue for each restaurant.
- The outer query uses RANK() to assign ranks.
- ORDER BY total_revenue DESC ranks the highest revenue-generating restaurant first.
- Restaurants with equal revenue receive the same rank.
#9. Calculate month-over-month revenue growth
WITH monthly_revenue AS (
    SELECT
        DATE_FORMAT(order_date, '%Y-%m') AS order_month,
        SUM(total_amount) AS total_revenue
    FROM orders
    WHERE order_status = 'Delivered'
    GROUP BY DATE_FORMAT(order_date, '%Y-%m')
)
SELECT
    order_month,
    total_revenue,
    LAG(total_revenue) OVER (
        ORDER BY order_month
    ) AS previous_month_revenue,
    ROUND(
        (
            total_revenue -
            LAG(total_revenue) OVER (
                ORDER BY order_month
            )
        ) * 100.0 /
        NULLIF(
            LAG(total_revenue) OVER (
                ORDER BY order_month
            ), 0
        ),
        2
    ) AS revenue_growth_percentage
FROM monthly_revenue
ORDER BY order_month;


# Concept: CTE, DATE_FORMAT(), SUM(), LAG(), Window Function, NULLIF(), Percentage Calculation

# Explanation:
- The CTE calculates monthly revenue.
- LAG() retrieves the previous month's revenue.
- The difference between current and previous revenue is used to calculate growth.
- NULLIF() prevents division by zero.
- The result identifies whether revenue increased or decreased compared with the previous month.
# Example:
Month	Revenue	Previous revenue	Growth
January	₹1,00,000	NULL	NULL
February	₹1,20,000	₹1,00,000	20%
March	₹1,50,000	₹1,20,000	25%

#10. Calculate revenue contribution percentage
SELECT
    r.restaurant_id,
    r.restaurant_name,
    SUM(o.total_amount) AS restaurant_revenue,
    ROUND(
        SUM(o.total_amount) * 100.0 /
        (
            SELECT SUM(total_amount)
            FROM orders
            WHERE order_status = 'Delivered'
        ),
        2
    ) AS revenue_contribution_percentage
FROM restaurants r
JOIN orders o
    ON r.restaurant_id = o.restaurant_id
WHERE o.order_status = 'Delivered'
GROUP BY
    r.restaurant_id,
    r.restaurant_name
ORDER BY revenue_contribution_percentage DESC;


# Concept: JOIN, SUM(), Subquery, GROUP BY, ROUND(), Percentage Calculation

# Explanation:
- Calculates the total revenue generated by each restaurant.
- The subquery calculates the overall revenue generated by all restaurants.
- Divides individual restaurant revenue by total business revenue.
- Multiplies by 100 to calculate the contribution percentage.
# Formula:
\[
\text{Revenue Contribution} =
\frac{\text{Restaurant Revenue}}{\text{Total Revenue}}\times100
\]

# Example:

If total business revenue is ₹5,00,000 and Restaurant A generates ₹1,00,000:

Revenue contribution = 20%.
