#12. Calculate cumulative revenue using window functions
SELECT
    DATE(order_date) AS order_day,
    SUM(total_amount) AS daily_revenue,
    SUM(SUM(total_amount)) OVER (
        ORDER BY DATE(order_date)
        ROWS BETWEEN UNBOUNDED PRECEDING
        AND CURRENT ROW
    ) AS cumulative_revenue
FROM orders
WHERE order_status = 'Delivered'
GROUP BY DATE(order_date)
ORDER BY order_day;


# Concept: SUM(), GROUP BY, Window Function, OVER(), ORDER BY, ROWS BETWEEN

# Explanation:
- First SUM() calculates the revenue generated each day.
- The window SUM() calculates the running total of revenue.
- UNBOUNDED PRECEDING starts the calculation from the first available date.
- CURRENT ROW calculates revenue up to the current date.
- Cumulative revenue keeps increasing as new daily revenue is added.
# Example:
