#Basic Level
#1. Calculate total order revenue
SELECT
    SUM(total_amount) AS total_revenue
FROM orders
WHERE order_status = 'Delivered';


# Concept: SUM(), WHERE, Aggregate Function

# Explanation:
- SUM() calculates the total revenue generated from orders.
- WHERE filters only successfully delivered orders.
- The result displays the overall revenue generated by the business.
